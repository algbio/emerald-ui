// Letter -> matrix row/column index, mirroring optimal_paths.cpp's LTA[26] table exactly
// (standard amino acids -> 0..19 in Ala,Arg,Asn,Asp,Cys,Gln,Glu,Gly,His,Ile,Leu,Lys,Met,Phe,
// Pro,Ser,Thr,Trp,Tyr,Val order; ambiguous/non-standard letters B,J,O,U,X,Z -> 20 ("Def")).
const AMINO_ACID_INDEX: Record<string, number> = {
  A: 0, R: 1, N: 2, D: 3, C: 4, Q: 5, E: 6, G: 7, H: 8, I: 9,
  L: 10, K: 11, M: 12, F: 13, P: 14, S: 15, T: 16, W: 17, Y: 18, V: 19,
  B: 20, J: 20, O: 20, U: 20, X: 20, Z: 20,
};

/** Returns the matrix row/column index for an amino acid letter (case-insensitive); 20 ("Def") for unknown letters. */
export function getAminoAcidIndex(letter: string): number {
  return AMINO_ACID_INDEX[letter.toUpperCase()] ?? 20;
}

/** Substitution score for a pair of residues under the given matrix type. */
export function getSubstitutionScore(a: string, b: string, matrixType: CostMatrixTypeValue): number {
  const matrix = SUBSTITUTION_MATRICES[matrixType] ?? SUBSTITUTION_MATRICES[CostMatrixType.BLOSUM62];
  return matrix[getAminoAcidIndex(a)][getAminoAcidIndex(b)];
}
